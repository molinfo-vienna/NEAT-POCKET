MODEL_ORDER = list(MODELS.keys())

OUTLIER_THRESHOLD = 3.5

METRIC_RE = re.compile(
    r"^(?P<name>[A-Za-z0-9_\-x ]+):\s*(?P<value>-?\d+(?:\.\d+)?)(?P<pct>%)?\s*$"
)

palette = sns.color_palette("rocket").as_hex()
COLORS = {
    "inliers": palette[5],
    "outliers": palette[2],
}


def parse_evaluation_results(path: Path) -> dict:
    """Parse a flat key: value evaluation_results.txt into a dict of floats."""
    metrics = {}
    for line in path.read_text().splitlines():
        m = METRIC_RE.match(line.strip())
        if not m:
            continue
        metrics[m.group("name").strip()] = float(m.group("value"))
    return metrics


def load_model_strain(model_name: str, dataset: str, rel_dir: str) -> pd.DataFrame:
    data_dir = INPUT_PATH / rel_dir / "conditional"
    rows = []
    for path in sorted(data_dir.glob("pocket_*/evaluation_results.txt")):
        metrics = parse_evaluation_results(path)
        if "strain" not in metrics:
            continue
        rows.append(
            {
                "model": model_name,
                "dataset": dataset,
                "pocket": path.parent.name,
                "strain": metrics["strain"],
                "clashes": metrics.get("clashes"),
            }
        )
    df = pd.DataFrame(rows)
    if df.empty:
        raise FileNotFoundError(
            f"No evaluation_results.txt with strain under {data_dir}"
        )
    return df


def flag_outliers(strain: pd.Series) -> pd.DataFrame:
    """Modified z-score on log10(strain); non-positive strains are clipped to 1e-12."""
    log_strain = np.log10(strain.clip(lower=1e-12))
    med = np.median(log_strain)
    mad = np.median(np.abs(log_strain - med))
    mad = mad if mad > 0 else 1e-12
    mod_z = 0.6745 * (log_strain - med) / mad
    return pd.DataFrame(
        {
            "log10_strain": log_strain,
            "mod_z": mod_z,
            "outlier_upper": mod_z > OUTLIER_THRESHOLD,
            "outlier_lower": mod_z < -OUTLIER_THRESHOLD,
            "outlier": mod_z.abs() > OUTLIER_THRESHOLD,
        },
        index=strain.index,
    )


def summarize_model(sub: pd.DataFrame) -> dict:
    strain = sub["strain"].astype(float)
    top1_idx = strain.idxmax()
    without_top1 = strain.drop(index=top1_idx)
    inliers = strain.loc[~sub["outlier"]]
    return {
        "dataset": sub["dataset"].iloc[0],
        "model": sub["model"].iloc[0],
        "n_pockets": len(strain),
        "mean": strain.mean(),
        "median": strain.median(),
        "top1": strain.loc[top1_idx],
        "top1_pocket": sub.loc[top1_idx, "pocket"],
        "mean_wo_top1": without_top1.mean(),
        "median_wo_top1": without_top1.median(),
        "n_outliers_upper": int(sub["outlier_upper"].sum()),
        "n_outliers_lower": int(sub["outlier_lower"].sum()),
        "mean_wo_outliers": inliers.mean(),
        "median_wo_outliers": inliers.median(),
    }


def plot_strain_energies(df: pd.DataFrame, path: Path) -> None:
    n_models = len(MODEL_ORDER)
    fig, axes = plt.subplots(1, n_models, figsize=(4 * n_models, 5), sharey="row")
    for ax, model in zip(axes, MODEL_ORDER):
        order = df.loc[df["model"] == model].sort_values("strain", ascending=False)
        colors = np.where(order["outlier"], COLORS["outliers"], COLORS["inliers"])
        ax.bar(range(len(order)), order["strain"].values, color=colors, width=1.0)
        ax.set_yscale("log")
        ax.set_title(model)
        ax.set_xlabel("Pockets (sorted)")
    axes[0].set_ylabel("Strain energy")
    plt.tight_layout()
    plt.savefig(path)
    plt.close(fig)


def main() -> None:
    flagged = []
    for model, (dataset, rel_dir) in MODELS.items():
        sub = load_model_strain(model, dataset, rel_dir)
        flagged.append(pd.concat([sub, flag_outliers(sub["strain"])], axis=1))
    df = pd.concat(flagged, ignore_index=True)

    logging.info("Pockets loaded per model:")
    logging.info(df.groupby("model", sort=False).size().to_string() + "\n")

    table = pd.DataFrame(
        [summarize_model(df.loc[df["model"] == model]) for model in MODEL_ORDER]
    )

    plot_strain_energies(df, OUTPUT_PATH / "strain_energies.png")

    energy_columns = [
        "mean", "median", "top1", "mean_wo_top1", "median_wo_top1",
        "mean_wo_outliers", "median_wo_outliers",
    ]
    table[energy_columns] = table[energy_columns].round().astype("int64")
    df["strain"] = df["strain"].round().astype("int64")

    df.to_csv(OUTPUT_PATH / "strain_energies_per_pocket.csv", index=False)
    table.to_csv(OUTPUT_PATH / "strain_energies_table.csv", index=False)

    with pd.option_context(
        "display.max_columns", None,
        "display.width", 250,
        "display.float_format", "{:,.2f}".format,
    ):
        logging.info("Aggregated strain energies (kcal/mol):")
        logging.info(table.to_string(index=False) + "\n")

        for model in MODEL_ORDER:
            outliers = df.loc[
                (df["model"] == model) & df["outlier"],
                ["pocket", "strain", "log10_strain", "mod_z", "clashes"],
            ].sort_values("strain", ascending=False)
            logging.info(f"=== {model}: {len(outliers)} outlier(s) ===")
            logging.info(
                (outliers.to_string(index=False) if len(outliers) else "  (none)")
                + "\n"
            )

    logging.info(f"Results written to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
