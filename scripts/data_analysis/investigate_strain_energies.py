"""
This script is used to investigate the PoseCheck strain energies of the molecules generated by models
trained on the CrossDocked and SPINDR datasets:
    - CrossDocked: Pocket2Mol, TargetDiff, DiffSBDD, DrugFlow, NEAT-PC (CrossDocked)
    - SPINDR: FLOWR, NEAT-PC (SPINDR)

For each model, the per-pocket average strain energies are read from
generated_data/<model>/conditional/pocket_*/evaluation_results.txt and aggregated across pockets.
Outlier pockets are detected with the modified z-score on log10-transformed strain energies:

    z_i = 0.6745 * (log10(e_i) - median(log10(e))) / MAD

where MAD is the median absolute deviation of the log-transformed strain energies. A pocket is an
upper-tail (lower-tail) outlier if z_i > 3.5 (z_i < -3.5). Non-positive strain energies are clipped
to 1e-12 before the log transform, so they are flagged as lower-tail outliers. Non-positive strain
energies are a consequence of a possible bug of the PoseCheck software, since they are unphysical.

For each model, the script reports the mean and median strain energy across pockets, the largest per-pocket
strain energy (top-1), the mean and median without the top-1 pocket, the number of upper- and
lower-tail outliers, and the mean and median without outliers. Energies are in kcal/mol and rounded
to the nearest integer in the outputs.

It produces the following outputs in the output/data_analysis/strain_energies directory:
    1. strain_energies.png: per-pocket strain energies for each model (sorted, log scale, outliers highlighted)
    2. strain_energies_table.csv: aggregated strain energies per model
    3. strain_energies_per_pocket.csv: per-pocket strain energies, modified z-scores and outlier flags
    4. strain_energies.log: aggregated strain energies and the list of outlier pockets per model

The script must be run from the repository root directory.
"""

